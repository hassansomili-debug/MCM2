CREATE TABLE IF NOT EXISTS consultation_lead_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  consultation_lead_id BIGINT NOT NULL,
  event_type TEXT NOT NULL,
  previous_status TEXT,
  new_status TEXT,
  note TEXT,
